#!/usr/bin/env node
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { deflateSync } from 'node:zlib'
import { fileURLToPath } from 'node:url'

function crcTable() {
  const table = new Uint32Array(256)
  for (let n = 0; n < 256; n++) {
    let c = n
    for (let k = 0; k < 8; k++) c = (c & 1) ? (0xEDB88320 ^ (c >>> 1)) : (c >>> 1)
    table[n] = c >>> 0
  }
  return table
}
const TABLE = crcTable()
function crc32(buf) {
  let crc = 0xFFFFFFFF
  for (let i = 0; i < buf.length; i++) crc = TABLE[(crc ^ buf[i]) & 0xFF] ^ (crc >>> 8)
  return (crc ^ 0xFFFFFFFF) >>> 0
}
function chunk(type, data) {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length, 0)
  const typeBuf = Buffer.from(type, 'ascii')
  const crcBuf = Buffer.alloc(4); crcBuf.writeUInt32BE(crc32(Buffer.concat([typeBuf, data])), 0)
  return Buffer.concat([len, typeBuf, data, crcBuf])
}
function makeRgbaPng(w, h, pixelFn) {
  // pixelFn(x, y) → [r, g, b, a]
  const sig = Buffer.from([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A])
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4)
  ihdr[8] = 8                    // bit depth 8
  ihdr[9] = 6                    // color type RGBA
  ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0
  const stride = 1 + w * 4
  const raw = Buffer.alloc(h * stride)
  for (let y = 0; y < h; y++) {
    raw[y * stride] = 0          // filter byte
    for (let x = 0; x < w; x++) {
      const [r, g, b, a] = pixelFn(x, y)
      const off = y * stride + 1 + x * 4
      raw[off] = r; raw[off + 1] = g; raw[off + 2] = b; raw[off + 3] = a
    }
  }
  const idat = deflateSync(raw)
  return Buffer.concat([sig, chunk('IHDR', ihdr), chunk('IDAT', idat), chunk('IEND', Buffer.alloc(0))])
}

// Brand glyph: a 5-dot "node + satellites" constellation defined in a 14x14
// design grid (same coordinates as packages/renderer/src/App.tsx's nav SVG)
// and scaled to the requested icon size with simple sub-pixel anti-aliasing.
const GLYPH_VIEW = 14
const GLYPH_DOTS = [
  [7,    7,    2.5],   // center node
  [7,    1.5,  1.5],   // top satellite
  [7,    12.5, 1.5],   // bottom
  [1.5,  7,    1.5],   // left
  [12.5, 7,    1.5],   // right
]

function makeBrandPng(size, [r, g, b]) {
  const scale = size / GLYPH_VIEW
  const dots = GLYPH_DOTS.map(([cx, cy, cr]) => [cx * scale, cy * scale, cr * scale])
  return makeRgbaPng(size, size, (x, y) => {
    let cover = 0
    for (const [cx, cy, cr] of dots) {
      const d = Math.hypot(x + 0.5 - cx, y + 0.5 - cy)
      // Soft 1-px edge: full inside cr-0.5, fades out by cr+0.5.
      const c = Math.max(0, Math.min(1, cr - d + 0.5))
      if (c > cover) cover = c
    }
    if (cover === 0) return [0, 0, 0, 0]
    return [r, g, b, Math.round(cover * 255)]
  })
}

const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(here, '../src/main/assets/tray-icon.ts')
mkdirSync(dirname(out), { recursive: true })

// Brand-glyph palette: the project's --accent (#6366f1 indigo) for the
// colour targets — saturated enough to read on both light and dark Linux/Win
// panels. The macOS template is pure white (Electron uses alpha to drive
// the OS auto-tint, so the RGB there is irrelevant).
const standard22 = makeBrandPng(22, [99, 102, 241]).toString('base64')
const standard44 = makeBrandPng(44, [99, 102, 241]).toString('base64')
const template22 = makeBrandPng(22, [255, 255, 255]).toString('base64')

const banner = `// Generated by apps/desktop/scripts/gen-tray-icon.mjs — placeholder tray icons.
// Replace this module (or swap to real PNG files + electron-vite asset copy) when
// real iconography is ready. tray.ts loads these via nativeImage.createFromBuffer.\n\n`

const body = [
  `export const TRAY_ICON_PNG_BASE64 = '${standard22}'`,
  `export const TRAY_ICON_2X_PNG_BASE64 = '${standard44}'`,
  `export const TRAY_ICON_TEMPLATE_PNG_BASE64 = '${template22}'`,
].join('\n') + '\n'

writeFileSync(out, banner + body)
console.log(`Wrote ${out}`)
